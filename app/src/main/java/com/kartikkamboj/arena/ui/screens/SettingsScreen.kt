/**
 * Appearance, session policy, local data and diagnostics.
 *
 * The diagnostics block is generated by [com.kartikkamboj.arena.di.Diagnostics], which only ever
 * emits device facts and counts — the diagnostics code path has no access to cookie values, and the
 * screen says so because it is true.
 */
@Composable
fun SettingsScreen(container: AppContainer, navigator: NavHostController) {
    val settings by container.settings.settings.collectAsStateWithLifecycle()
    val registry by container.accounts.registry.collectAsStateWithLifecycle()
    val scope = rememberCoroutineScope()

    var report by remember { mutableStateOf<DiagnosticsReport?>(null) }
    var busy by remember { mutableStateOf(false) }
    var confirmWipeData by remember { mutableStateOf(false) }
    var confirmLogoutAll by remember { mutableStateOf(false) }
    var message by remember { mutableStateOf<String?>(null) }

    LaunchedEffect(Unit) {
        busy = true
        report = container.diagnostics.report()
        busy = false
    }

    LazyColumn(
        modifier = Modifier
            .fillMaxSize()
            .background(MaterialTheme.colorScheme.background),
        contentPadding = PaddingValues(bottom = 28.dp),
    ) {
        item {
            SectionTitle(
                title = "Settings",
                subtitle = "v${BuildConfig.VERSION_NAME} · ${if (BuildConfig.DEBUG) "debug build" else "release build"}",
            )
        }

        item {
            GroupCard(title = "Appearance") {
                ChoiceRow(
                    label = "Theme",
                    hint = "Dark is the design default; light keeps the same accents.",
                    options = ThemeMode.entries.map { it.displayName() to it.name },
                    selected = settings.themeMode.name,
                    onSelect = { key ->
                        container.settings.update { it.copy(themeMode = ThemeMode.valueOf(key)) }
                    },
                )
            }
        }

        item {
            GroupCard(title = "Chat") {
                ChoiceRow(
                    label = "Default mode",
                    hint = "Used when the app opens Arena for a slot.",
                    options = ArenaMode.entries.map { it.label to it.name },
                    selected = settings.defaultMode.name,
                    onSelect = { key ->
                        container.settings.update { it.copy(defaultMode = ArenaMode.valueOf(key)) }
                    },
                )
                Spacer(Modifier.height(12.dp))
                ToggleRow(
                    title = "Native draft bar",
                    subtitle = "Puts your draft into the page's own composer. Never submits it — " +
                        "sending always happens on the page.",
                    checked = settings.nativeComposerEnabled,
                    onToggle = { value -> container.settings.update { it.copy(nativeComposerEnabled = value) } },
                )
                Spacer(Modifier.height(10.dp))
                ToggleRow(
                    title = "Screenshot protection",
                    subtitle = "Blocks screen capture and hides content in the recent-apps preview.",
                    checked = settings.screenshotProtection,
                    onToggle = { value -> container.settings.update { it.copy(screenshotProtection = value) } },
                )
            }
        }

        item {
            GroupCard(title = "Accounts & sessions") {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(8.dp),
                ) {
                    Text(
                        text = AccountPolicy.statusSummary(registry.accounts),
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        modifier = Modifier.weight(1f),
                    )
                    GhostButton(
                        text = "Manage",
                        onClick = { navigator.navigate(ArenaDestination.ACCOUNTS.route) { launchSingleTop = true } },
                    )
                }
                Spacer(Modifier.height(12.dp))
                ToggleRow(
                    title = "Wipe site storage on switch",
                    subtitle = "Clears localStorage, IndexedDB and the HTTP cache when you change slot, " +
                        "so the next slot cannot read the previous one's client state. Turn it off only " +
                        "if you accept that leak.",
                    checked = settings.isolateSiteStorageOnSwitch,
                    onToggle = { value -> container.settings.update { it.copy(isolateSiteStorageOnSwitch = value) } },
                )
                Spacer(Modifier.height(10.dp))
                ToggleRow(
                    title = "Allow page storage (DOM storage)",
                    subtitle = "Arena needs this to keep you signed in. Disabling it will break most logins.",
                    checked = settings.domStorageEnabled,
                    onToggle = { value -> container.settings.update { it.copy(domStorageEnabled = value) } },
                )
                Spacer(Modifier.height(10.dp))
                ToggleRow(
                    title = "Verify session after each load",
                    subtitle = "Re-runs the read-only signed-in check when a page settles.",
                    checked = settings.autoReprobe,
                    onToggle = { value -> container.settings.update { it.copy(autoReprobe = value) } },
                )
                Spacer(Modifier.height(10.dp))
                ToggleRow(
                    title = "Erase cookies on logout",
                    subtitle = "Recommended. Turning it off leaves the jar on disk until it ages out.",
                    checked = settings.wipeJarOnLogout,
                    onToggle = { value -> container.settings.update { it.copy(wipeJarOnLogout = value) } },
                )
                Spacer(Modifier.height(12.dp))
                StepperRow(
                    title = "Local session retention",
                    subtitle = "How long a stored jar may be reused before the app refuses it and asks " +
                        "you to sign in again. This is a privacy guard, not Arena's own expiry.",
                    value = settings.sessionTtlHours,
                    suffix = "h",
                    range = AppSettings.MIN_TTL_HOURS..AppSettings.MAX_TTL_HOURS,
                    onValueChange = { hours -> container.settings.update { it.copy(sessionTtlHours = hours) } },
                )
            }
        }

        item {
            GroupCard(title = "Local data") {
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    GhostButton(
                        text = "Clear history",
                        icon = Icons.Filled.Delete,
                        onClick = {
                            scope.launch {
                                val removed = container.history.clearAll()
                                message = "Removed $removed local record(s)."
                            }
                        },
                    )
                    GhostButton(
                        text = "Sign out all slots",
                        icon = Icons.Filled.Lock,
                        onClick = { confirmLogoutAll = true },
                    )
                }
                Spacer(Modifier.height(10.dp))
                GhostButton(
                    text = "Delete all app data",
                    icon = Icons.Filled.Delete,
                    destructive = true,
                    modifier = Modifier.fillMaxWidth(),
                    onClick = { confirmWipeData = true },
                )
                message?.let { text ->
                    Spacer(Modifier.height(10.dp))
                    Text(
                        text = text,
                        style = MaterialTheme.typography.labelMedium,
                        color = ArenaPalette.Cyan,
                    )
                }
            }
        }

        item {
            GroupCard(
                title = "Connection diagnostics",
                trailing = {
                    TextButton(onClick = {
                        scope.launch {
                            busy = true
                            report = container.diagnostics.report()
                            busy = false
                        }
                    }) {
                        Icon(
                            imageVector = Icons.Filled.Refresh,
                            contentDescription = null,
                            modifier = Modifier.size(15.dp),
                            tint = MaterialTheme.colorScheme.primary,
                        )
                        Spacer(Modifier.width(6.dp))
                        Text("Refresh", style = MaterialTheme.typography.labelLarge)
                    }
                },
            ) {
                Text(
                    text = "Counts, versions and capability checks only. Cookie values, tokens and " +
                        "typed text are never read into this list.",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
                Spacer(Modifier.height(10.dp))
                if (busy && report == null) {
                    Text("Reading…", style = MaterialTheme.typography.labelMedium, color = ArenaPalette.Cyan)
                }
                report?.lines?.forEach { line ->
                    Row(
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(vertical = 4.dp),
                        verticalAlignment = Alignment.Top,
                    ) {
                        Text(
                            text = line.label,
                            style = MaterialTheme.typography.labelMedium,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            modifier = Modifier
                                .width(150.dp)
                                .padding(top = 2.dp),
                        )
                        Text(
                            text = line.value,
                            style = MaterialTheme.typography.bodySmall,
                            color = when (line.tone) {
                                Tone.GOOD -> ArenaPalette.Mint
                                Tone.WARN -> ArenaPalette.Amber
                                Tone.BAD -> ArenaPalette.Rose
                                Tone.NEUTRAL -> MaterialTheme.colorScheme.onBackground
                            },
                            modifier = Modifier.weight(1f),
                        )
                    }
                }
                report?.let { generated ->
                    Spacer(Modifier.height(8.dp))
                    Text(
                        text = "Generated ${relativeAge(generated.generatedAtMillis, container.clock.nowMillis())}",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                }
            }
        }

        item {
            GroupCard(title = "About") {
                Text(
                    text = "Arena AI · AI Chat Experience",
                    style = MaterialTheme.typography.titleMedium,
                    color = MaterialTheme.colorScheme.onBackground,
                )
                Spacer(Modifier.height(6.dp))
                Text(
                    text = "An independent Android client for the public arena.ai web app. Not " +
                        "affiliated with, endorsed by, or operated by Arena. All model answers come " +
                        "from Arena itself; this app adds no model of its own and stores no prompts or " +
                        "responses.",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
                Spacer(Modifier.height(10.dp))
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    InfoChip(label = "Terms", leadingIcon = Icons.Filled.OpenInNew, onClick = { container.session.handOffTo(ArenaUrls.TERMS) })
                    InfoChip(label = "Privacy", leadingIcon = Icons.Filled.OpenInNew, onClick = { container.session.handOffTo(ArenaUrls.PRIVACY) })
                }
                Spacer(Modifier.height(10.dp))
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Icon(
                        imageVector = Icons.Filled.Shield,
                        contentDescription = null,
                        tint = ArenaPalette.Mint,
                        modifier = Modifier.size(15.dp),
                    )
                    Spacer(Modifier.width(8.dp))
                    Text(
                        text = "No analytics, no crash SDK, no ad identifiers, no keys in the APK.",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                }
                Spacer(Modifier.height(8.dp))
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Icon(
                        imageVector = Icons.Filled.Info,
                        contentDescription = null,
                        tint = MaterialTheme.colorScheme.onSurfaceVariant,
                        modifier = Modifier.size(15.dp),
                    )
                    Spacer(Modifier.width(8.dp))
                    Text(
                        text = "Package ${BuildConfig.APPLICATION_ID} · code ${BuildConfig.VERSION_CODE}",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                }
            }
        }
    }

    if (confirmLogoutAll) {
        AlertDialog(
            onDismissRequest = { confirmLogoutAll = false },
            title = { Text("Sign out every slot?") },
            text = {
                Text(
                    "Each slot's stored cookies are deleted and its web view is destroyed. Arena keeps " +
                        "your account and history; you can sign in again any time.",
                )
            },
            confirmButton = {
                TextButton(onClick = {
                    scope.launch {
                        registry.accounts.forEach { container.accounts.logout(it.slot) }
                        container.rateLimits.clearAll()
                        container.session.destroyView()
                        confirmLogoutAll = false
                        message = "Signed out ${registry.accounts.size} slot(s)."
                    }
                }) { Text("Sign out all") }
            },
            dismissButton = { TextButton(onClick = { confirmLogoutAll = false }) { Text("Cancel") } },
        )
    }

    if (confirmWipeData) {
        AlertDialog(
            onDismissRequest = { confirmWipeData = false },
            title = { Text("Delete all app data?") },
            text = {
                Text(
                    "Removes every local record: account slots, encrypted cookie jars, thread " +
                        "pointers and the model list. Site storage is cleared too. This cannot be " +
                        "undone, and it does not touch your Arena account.",
                )
            },
            confirmButton = {
                TextButton(onClick = {
                    scope.launch {
                        val result = container.clearLocalData(includeSessions = true)
                        container.session.destroyView()
                        confirmWipeData = false
                        message = "Removed ${result.threadsRemoved} record(s) and " +
                            "${result.sessionDataWiped} session blob(s)."
                        report = container.diagnostics.report()
                    }
                }) { Text("Delete everything", color = ArenaPalette.Rose) }
            },
            dismissButton = { TextButton(onClick = { confirmWipeData = false }) { Text("Cancel") } },
        )
    }
}

@Composable
private fun GroupCard(
    title: String,
    trailing: @Composable (() -> Unit)? = null,
    content: @Composable ColumnScope.() -> Unit,
) {
    ArenaCard(
        modifier = Modifier
            .fillMaxWidth()
            .padding(horizontal = 20.dp, vertical = 6.dp),
    ) {
        Row(verticalAlignment = Alignment.CenterVertically) {
            Text(
                text = title,
                style = MaterialTheme.typography.titleMedium,
                color = MaterialTheme.colorScheme.onBackground,
                modifier = Modifier.weight(1f),
            )
            trailing?.invoke()
        }
        Spacer(Modifier.height(10.dp))
        content()
    }
}

@Composable
private fun ToggleRow(
    title: String,
    subtitle: String,
    checked: Boolean,
    onToggle: (Boolean) -> Unit,
) {
    Row(
        modifier = Modifier
            .fillMaxWidth()
            .clip(RoundedCornerShape(14.dp))
            .clickable { onToggle(!checked) }
            .padding(vertical = 6.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Column(modifier = Modifier.weight(1f)) {
            Text(
                text = title,
                style = MaterialTheme.typography.titleSmall,
                color = MaterialTheme.colorScheme.onBackground,
            )
            Spacer(Modifier.height(3.dp))
            Text(
                text = subtitle,
                style = MaterialTheme.typography.labelSmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        }
        Spacer(Modifier.width(12.dp))
        Switch(
            checked = checked,
            onCheckedChange = onToggle,
            colors = SwitchDefaults.colors(
                checkedTrackColor = ArenaPalette.Violet,
                checkedThumbColor = Color(0xFF0B0B0D),
                uncheckedTrackColor = MaterialTheme.colorScheme.surfaceVariant,
                uncheckedThumbColor = MaterialTheme.colorScheme.onSurfaceVariant,
            ),
        )
    }
}

@Composable
private fun ChoiceRow(
    label: String,
    hint: String,
    options: List<Pair<String, String>>,
    selected: String,
    onSelect: (String) -> Unit,
) {
    Column(modifier = Modifier.fillMaxWidth()) {
        Text(
            text = label,
            style = MaterialTheme.typography.titleSmall,
            color = MaterialTheme.colorScheme.onBackground,
        )
        Text(
            text = hint,
            style = MaterialTheme.typography.labelSmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
        Spacer(Modifier.height(8.dp))
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            options.forEach { (title, key) ->
                InfoChip(
                    label = title,
                    selected = key == selected,
                    onClick = { onSelect(key) },
                )
            }
        }
    }
}

@Composable
private fun StepperRow(
    title: String,
    subtitle: String,
    value: Int,
    suffix: String,
    range: IntRange,
    onValueChange: (Int) -> Unit,
) {
    Row(
        modifier = Modifier.fillMaxWidth(),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Column(modifier = Modifier.weight(1f)) {
            Text(text = title, style = MaterialTheme.typography.titleSmall, color = MaterialTheme.colorScheme.onBackground)
            Spacer(Modifier.height(3.dp))
            Text(text = subtitle, style = MaterialTheme.typography.labelSmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
        }
        Spacer(Modifier.width(10.dp))
        StepperButton(Icons.Filled.Remove, enabled = value > range.first) { onValueChange(value - 1) }
        Box(
            modifier = Modifier
                .width(64.dp)
                .height(38.dp)
                .clip(RoundedCornerShape(12.dp))
                .background(MaterialTheme.colorScheme.surfaceVariant)
                .border(BorderStroke(1.dp, MaterialTheme.colorScheme.outline), RoundedCornerShape(12.dp)),
            contentAlignment = Alignment.Center,
        ) {
            Text(
                text = "$value$suffix",
                style = MaterialTheme.typography.titleSmall,
                fontWeight = FontWeight.SemiBold,
                color = MaterialTheme.colorScheme.onBackground,
            )
        }
        StepperButton(Icons.Filled.Add, enabled = value < range.last) { onValueChange(value + 1) }
    }
}

@Composable
private fun StepperButton(icon: androidx.compose.ui.graphics.vector.ImageVector, enabled: Boolean, onClick: () -> Unit) {
    val shape = RoundedCornerShape(12.dp)
    Box(
        modifier = Modifier
            .size(38.dp)
            .clip(shape)
            .background(if (enabled) ArenaPalette.SurfaceVariant else MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.4f))
            .clickable(enabled = enabled, onClick = onClick),
        contentAlignment = Alignment.Center,
    ) {
        Icon(
            imageVector = icon,
            contentDescription = null,
            tint = if (enabled) MaterialTheme.colorScheme.onBackground else ArenaPalette.TextFaint,
            modifier = Modifier.size(16.dp),
        )
    }
}

private fun ThemeMode.displayName(): String = when (this) {
    ThemeMode.SYSTEM -> "System"
    ThemeMode.DARK -> "Dark"
    ThemeMode.LIGHT -> "Light"
}
