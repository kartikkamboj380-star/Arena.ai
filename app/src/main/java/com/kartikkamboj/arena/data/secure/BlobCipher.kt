package com.kartikkamboj.arena.data.secure

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec
import javax.crypto.spec.SecretKeySpec

/**
 * Encrypts what the app must keep on disk: per-slot cookie jars and the probe cache.
 *
 * The production implementation puts the key in the Android Keystore and never lets it out;
 * payload layout is `IV(12) || ciphertext+tag`, AES/GCM/NoPadding, 256-bit key,
 * `setRandomizedEncryptionRequired(true)` so a fresh IV is generated by the provider for every
 * call. The test implementation is the same algorithm with a process-local key, which is what
 * allows the file format itself to be unit-tested without a device.
 */
interface BlobCipher {
    /** Stable, non-secret identifier shown on the diagnostics screen. */
    val keyId: String

    /** False when the key lives outside the Android Keystore (tests, or keystore unavailable). */
    val hardwareBacked: Boolean

    fun encrypt(plain: ByteArray): ByteArray

    /** Null when the payload cannot be authenticated or was written under a different key. */
    fun decrypt(payload: ByteArray): ByteArray?

    fun destroyKey()
}

private const val TRANSFORMATION = "AES/GCM/NoPadding"
private const val IV_LENGTH = 12
private const val TAG_BITS = 128

class KeystoreBlobCipher(context: Context) : BlobCipher {

    override val keyId: String = ALIAS
    override val hardwareBacked: Boolean = true

    /** Whether the app's key has been created yet (first use lazily creates it). */
    fun keyExists(): Boolean = runCatching {
        KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }.containsAlias(ALIAS)
    }.getOrDefault(false)

    override fun encrypt(plain: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, obtainKey())
        val body = cipher.doFinal(plain)
        return cipher.iv + body
    }

    override fun decrypt(payload: ByteArray): ByteArray? {
        if (payload.size <= IV_LENGTH) return null
        return runCatching {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(
                Cipher.DECRYPT_MODE,
                obtainKey(),
                GCMParameterSpec(TAG_BITS, payload.copyOfRange(0, IV_LENGTH)),
            )
            cipher.doFinal(payload, IV_LENGTH, payload.size - IV_LENGTH)
        }.getOrNull()
    }

    override fun destroyKey() {
        runCatching {
            KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }.deleteEntry(ALIAS)
        }
    }

    private fun obtainKey(): SecretKey {
        val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        (keyStore.getKey(ALIAS, null) as? SecretKey)?.let { return it }

        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        generator.init(
            KeyGenParameterSpec.Builder(
                ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .setRandomizedEncryptionRequired(true)
                .setUserAuthenticationRequired(false)
                .build(),
        )
        return generator.generateKey()
    }

    companion object {
        const val ANDROID_KEYSTORE = "AndroidKeyStore"
        const val ALIAS = "arena_ai_session_blob_key"
    }
}

/** Test / fallback cipher: same file format, key never persists. */
class SoftwareGcmCipher(keyBytes: ByteArray) : BlobCipher {
    private val key: SecretKey = SecretKeySpec(keyBytes, "AES")

    override val keyId: String = "software-aes-gcm"
    override val hardwareBacked: Boolean = false

    override fun encrypt(plain: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key)
        return cipher.iv + cipher.doFinal(plain)
    }

    override fun decrypt(payload: ByteArray): ByteArray? {
        if (payload.size <= IV_LENGTH) return null
        return runCatching {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(
                Cipher.DECRYPT_MODE,
                key,
                GCMParameterSpec(TAG_BITS, payload.copyOfRange(0, IV_LENGTH)),
            )
            cipher.doFinal(payload, IV_LENGTH, payload.size - IV_LENGTH)
        }.getOrNull()
    }

    override fun destroyKey() = Unit
}
